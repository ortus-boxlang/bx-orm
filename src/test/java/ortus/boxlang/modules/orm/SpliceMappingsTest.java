package ortus.boxlang.modules.orm;

import static com.google.common.truth.Truth.assertThat;

import java.io.StringReader;
import java.nio.file.Path;
import java.util.List;

import javax.xml.parsers.DocumentBuilderFactory;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.NodeList;
import org.xml.sax.InputSource;

import ortus.boxlang.modules.orm.mapping.EntityRecord;
import ortus.boxlang.modules.orm.mapping.MappingXMLWriter;

/**
 * The text fast path that merges generated entity mappings into one {@code <entity-mappings>} document.
 */
public class SpliceMappingsTest {

	private static final String NS = MappingXMLWriter.ORM_NAMESPACE;

	/** A mapping in the shape MappingGenerator serializes: declaration, comment, default-namespace root, one entity. */
	private static String mapping( String entity ) {
		return """
		       <?xml version="1.0" encoding="UTF-8" standalone="no"?>
		       <!--
		       ~ Generated by the Ortus BoxLang ORM module.
		       --><entity-mappings xmlns="%s" version="7.0">
		           <entity class="facade.%s" name="%s">
		               <table name="t_%s"/>
		               <attributes>
		                   <id name="id">
		                       <unsaved-value>null</unsaved-value>
		                   </id>
		               </attributes>
		           </entity>
		       </entity-mappings>
		       """.formatted( NS, entity, entity, entity );
	}

	private static EntityRecord record( String name, String xml ) {
		return new EntityRecord( name, "models." + name ).setXmlMapping( xml );
	}

	private static Document parse( String xml ) throws Exception {
		DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
		factory.setNamespaceAware( true );
		return factory.newDocumentBuilder().parse( new InputSource( new StringReader( xml ) ) );
	}

	@DisplayName( "It merges generated mappings into one namespaced document, in order" )
	@Test
	public void testSplice() throws Exception {
		String combined = SessionFactoryBuilder
		    .spliceGeneratedMappings( List.of( record( "Parent", mapping( "Parent" ) ), record( "Child", mapping( "Child" ) ) ) );
		assertThat( combined ).isNotNull();

		Document doc = parse( combined );
		assertThat( doc.getDocumentElement().getNamespaceURI() ).isEqualTo( NS );
		assertThat( doc.getDocumentElement().getAttribute( "version" ) ).isEqualTo( MappingXMLWriter.ORM_VERSION );
		NodeList entities = doc.getElementsByTagNameNS( NS, "entity" );
		assertThat( entities.getLength() ).isEqualTo( 2 );
		assertThat( ( ( Element ) entities.item( 0 ) ).getAttribute( "name" ) ).isEqualTo( "Parent" );
		assertThat( ( ( Element ) entities.item( 1 ) ).getAttribute( "name" ) ).isEqualTo( "Child" );
		assertThat( doc.getElementsByTagNameNS( NS, "unsaved-value" ).getLength() ).isEqualTo( 2 );
	}

	@DisplayName( "It falls back (returns null) for mappings it did not write" )
	@Test
	public void testFallback() {
		// A prefixed namespace
		String prefixed = "<?xml version=\"1.0\"?><orm:entity-mappings xmlns:orm=\"" + NS + "\" version=\"7.0\"><orm:entity name=\"A\"/></orm:entity-mappings>";
		assertThat( SessionFactoryBuilder.spliceGeneratedMappings( List.of( record( "A", prefixed ) ) ) ).isNull();

		// Something other than <entity> under the root
		String other = "<entity-mappings xmlns=\"" + NS + "\" version=\"7.0\"><sequence-generator name=\"s\"/><entity name=\"A\"/></entity-mappings>";
		assertThat( SessionFactoryBuilder.spliceGeneratedMappings( List.of( record( "A", other ) ) ) ).isNull();

		// A mapping that only exists on disk (generateMappings=false)
		EntityRecord onDisk = new EntityRecord( "B", "models.B" ).setXmlFilePath( Path.of( "B.orm.xml" ) );
		assertThat( SessionFactoryBuilder.spliceGeneratedMappings( List.of( onDisk ) ) ).isNull();
	}
}
