package ortus.boxlang.modules.orm.statics;

import static com.google.common.truth.Truth.assertThat;

import java.nio.file.Paths;

import org.junit.jupiter.api.AfterAll;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.TestInstance;

import ortus.boxlang.modules.orm.config.ORMKeys;
import ortus.boxlang.runtime.BoxRuntime;
import ortus.boxlang.runtime.context.RequestBoxContext;
import ortus.boxlang.runtime.context.ScriptingRequestBoxContext;
import ortus.boxlang.runtime.modules.ModuleRecord;
import ortus.boxlang.runtime.scopes.IScope;
import ortus.boxlang.runtime.scopes.Key;
import ortus.boxlang.runtime.scopes.VariablesScope;

/**
 * {@code ormSettings.staticMethods = false} leaves entity classes untouched. Uses its own embedded Derby application
 * ({@code src/test/resources/staticOffApp}), so it runs without a database server.
 */
@TestInstance( TestInstance.Lifecycle.PER_CLASS )
public class StaticMethodsOffTest {

	private static BoxRuntime	instance;

	private RequestBoxContext	context;
	private IScope				variables;

	@BeforeAll
	public void setUp() {
		instance = BoxRuntime.getInstance( false );

		if ( !instance.getModuleService().hasModule( ORMKeys.moduleName ) ) {
			ModuleRecord ormModuleRecord = new ModuleRecord( Paths.get( "./build/module" ).toAbsolutePath().toString() );
			instance.getModuleService().getRegistry().put( ORMKeys.moduleName, ormModuleRecord );
			ormModuleRecord
			    .loadDescriptor( instance.getRuntimeContext() )
			    .register( instance.getRuntimeContext() )
			    .activate( instance.getRuntimeContext() );
		}

		context = new ScriptingRequestBoxContext( instance.getRuntimeContext(), false );
		RequestBoxContext.setCurrent( context );
		context.loadApplicationDescriptor( Paths.get( "src/test/resources/staticOffApp/index.bxs" ).toAbsolutePath().toUri() );
		context.getApplicationListener().onRequestStart( context, null );
		variables = context.getScopeNearby( VariablesScope.name );
	}

	@AfterAll
	public void teardown() {
		if ( context != null ) {
			context.getApplicationListener().onRequestEnd( context, null );
			RequestBoxContext.removeCurrent();
			context.shutdown();
		}
		instance.getApplicationService().shutdownApplication( Key.of( "BXORMStaticOffTest" ) );
	}

	@DisplayName( "With staticMethods = false, entity classes get no static methods, even after an instance is created" )
	@Test
	public void testNoStaticMethods() {
		// @formatter:off
		instance.executeSource( """
			g = entityNew( "Gizmo", { name : "one" } );
			try { root.models.Gizmo::get( 1 ); outcome = "ADDED"; } catch ( any e ) { outcome = "NOT ADDED"; }
			byBif = isNull( entityLoadByPK( "Gizmo", 1 ) );
		""", context );
		// @formatter:on
		assertThat( variables.getAsString( Key.of( "outcome" ) ) ).isEqualTo( "NOT ADDED" );
		assertThat( variables.get( Key.of( "byBif" ) ) ).isEqualTo( true );
	}
}
